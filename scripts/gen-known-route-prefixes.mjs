#!/usr/bin/env node

/**
 * Generate the known route-prefix manifest
 *
 * Emits src/generated/known-route-prefixes.ts — the set of valid top-level
 * URL segments, derived from src/app (with route groups expanded one level)
 * and top-level public/ entries.
 *
 * Middleware uses this to answer "can this path possibly exist?" for agent
 * requests: a GET whose first segment is not in this set is a guaranteed
 * 404, so middleware can serve a short markdown 404 body to non-browser
 * clients without waiting for the router. Paths under a known prefix are
 * never touched — their 404s still come from the designed not-found page.
 *
 * Run after adding or removing a top-level route or public/ file:
 *   node scripts/gen-known-route-prefixes.mjs
 *
 * Drift is guarded by src/__tests__/generated/known-route-prefixes.test.ts,
 * which recomputes this set from the filesystem and fails CI on mismatch.
 *
 * Copyright (c) 2019-2025 Mark Sandford
 * Licensed under the MIT License. See LICENSE and NOTICE files.
 */

import fs from 'fs/promises';
import path from 'path';

const APP_DIR = path.join(process.cwd(), 'src', 'app');
const PUBLIC_DIR = path.join(process.cwd(), 'public');
const OUT_FILE = path.join(process.cwd(), 'src', 'generated', 'known-route-prefixes.ts');

/** Collect top-level URL segments from src/app, expanding (group) dirs. */
export async function collectPrefixes() {
  const prefixes = new Set();

  async function addSegmentsFrom(dir) {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;
      const name = entry.name;
      if (name.startsWith('(') && name.endsWith(')')) {
        // Route group: its children are top-level paths.
        await addSegmentsFrom(path.join(dir, name));
      } else if (name.startsWith('[')) {
        // A dynamic segment at the top level would make every path
        // potentially valid — refuse to generate rather than emit a
        // manifest that silently 404s real pages.
        throw new Error(
          `Top-level dynamic segment ${name} in ${dir}: the known-prefix 404 shortcut is unsafe. Remove it or rework the middleware check.`
        );
      } else if (name !== 'api') {
        prefixes.add(name.toLowerCase());
      } else {
        prefixes.add('api');
      }
    }
  }

  await addSegmentsFrom(APP_DIR);

  // Top-level public/ files and directories are also valid first segments.
  // Dotfiles (.DS_Store etc.) are OS noise, not routes; .well-known is
  // covered by the extras below.
  for (const entry of await fs.readdir(PUBLIC_DIR, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    prefixes.add(entry.name.toLowerCase());
  }

  // Framework/platform paths that never come from src/app or public/:
  // Next internals, metadata routes, and next.config rewrite sources
  // (rewrites run AFTER middleware, so /lite/* must be claimed here).
  for (const extra of [
    '_next',
    '.well-known',
    'sitemap.xml',
    'sitemap-images.xml',
    'opengraph-image',
    'icon-192.png',
    'icon-512.png',
    'monitoring',
    'lite',
  ]) {
    prefixes.add(extra);
  }

  return [...prefixes].sort();
}

async function main() {
  const prefixes = await collectPrefixes();

  const body = `/**
 * AUTO-GENERATED by scripts/gen-known-route-prefixes.mjs — do not edit.
 *
 * Valid top-level URL segments, from src/app (route groups expanded) and
 * public/. Middleware treats a GET whose first segment is absent from this
 * set as a guaranteed 404 and can answer agents with a markdown body.
 * Drift-guarded by src/__tests__/generated/known-route-prefixes.test.ts.
 */

export const KNOWN_ROUTE_PREFIXES: ReadonlySet<string> = new Set([
${prefixes.map(p => `  '${p}',`).join('\n')}
]);
`;

  await fs.writeFile(OUT_FILE, body);
  console.log(`Wrote ${prefixes.length} prefixes to ${path.relative(process.cwd(), OUT_FILE)}`);
}

const isDirectRun = process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]));
if (isDirectRun) {
  main().catch(err => {
    console.error(err);
    process.exit(1);
  });
}
