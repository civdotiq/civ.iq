/**
 * Civic Brief Assembler
 *
 * Orchestrates data fetch → statistics → prompt → AI → fallback to produce
 * a single-page civic intelligence brief for any representative.
 *
 * Pattern: CivicAlignmentAnalyzer (cache check → parallel fetch → pre-compute → AI → fallback)
 */

